// Command sdkgen generates the client, then partitions declarations by API domain.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const header = "// Code generated by sdkgen (oapi-codegen); DO NOT EDIT.\n\npackage pennylane\n\n"

var domains = map[string]string{
	"bank_accounts": "banking", "bank_establishments": "banking", "transactions": "banking",
	"billing_email_templates": "subscriptions", "billing_subscriptions": "subscriptions",
	"categories": "categories", "category_groups": "categories",
	"commercial_documents": "commercial_documents",
	"company":              "company", "me": "company", "pa_registrations": "company",
	"customers": "customers", "company_customers": "customers", "individual_customers": "customers",
	"customer_invoices": "customer_invoices", "customer_invoice_templates": "customer_invoices",
	"exports": "accounting", "fiscal_years": "accounting", "journals": "accounting", "trial_balance": "accounting",
	"ledger_accounts": "accounting", "ledger_attachments": "accounting", "ledger_entries": "accounting",
	"ledger_entries_categories": "accounting", "ledger_entry_lines": "accounting", "ledger_entry_lines_categories": "accounting",
	"file_attachments": "attachments", "gocardless_mandates": "mandates", "pro_account": "mandates", "sepa_mandates": "mandates",
	"products": "products", "purchase_requests": "purchase_requests", "quotes": "quotes",
	"supplier_invoices": "supplier_invoices", "suppliers": "suppliers", "webhook_subscriptions": "webhooks",
}

type operation struct {
	OperationID string `json:"operationId"`
}

func operationDomains(spec []byte) (map[string]string, error) {
	var doc struct {
		Paths map[string]map[string]operation
	}
	if err := json.Unmarshal(spec, &doc); err != nil {
		return nil, err
	}
	result := map[string]string{}
	for path, methods := range doc.Paths {
		parts := strings.Split(strings.TrimPrefix(path, "/api/external/v2/"), "/")
		resource := parts[0]
		if resource == "changelogs" && len(parts) > 1 {
			resource = parts[1]
		}
		domain, ok := domains[resource]
		if !ok {
			return nil, fmt.Errorf("unmapped API resource: %s", path)
		}
		for _, op := range methods {
			if op.OperationID == "" {
				continue
			}
			words := strings.Split(op.OperationID, "-")
			for i, w := range words {
				words[i] = strings.ToUpper(w[:1]) + w[1:]
			}
			result[strings.Join(words, "")] = domain
		}
	}
	return result, nil
}

// split preserves every declaration verbatim; only file headers and imports change.
func split(src, spec []byte) (map[string][]byte, error) {
	ops, err := operationDomains(spec)
	if err != nil {
		return nil, err
	}
	names := make([]string, 0, len(ops))
	for name := range ops {
		names = append(names, name)
	}
	sort.Slice(names, func(i, j int) bool {
		if len(names[i]) == len(names[j]) {
			return names[i] < names[j]
		}
		return len(names[i]) > len(names[j])
	})
	domainOf := func(name string) string {
		for _, op := range names {
			for _, prefix := range []string{"", "New", "Parse"} {
				if strings.HasPrefix(name, prefix+op) {
					return ops[op]
				}
			}
		}
		return "common"
	}
	fs := token.NewFileSet()
	f, err := parser.ParseFile(fs, "api.gen.go", src, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	bodies := map[string]*bytes.Buffer{}
	used := map[string]map[string]bool{}
	for _, decl := range f.Decls {
		start := decl.Pos()
		name := ""
		switch d := decl.(type) {
		case *ast.GenDecl:
			if d.Tok == token.IMPORT {
				continue
			}
			if d.Doc != nil {
				start = d.Doc.Pos()
			}
			switch s := d.Specs[0].(type) {
			case *ast.TypeSpec:
				name = s.Name.Name
			case *ast.ValueSpec:
				name = s.Names[0].Name
			}
		case *ast.FuncDecl:
			if d.Doc != nil {
				start = d.Doc.Pos()
			}
			name = d.Name.Name
			if d.Recv != nil {
				r := d.Recv.List[0].Type
				if star, ok := r.(*ast.StarExpr); ok {
					r = star.X
				}
				if id, ok := r.(*ast.Ident); ok && domainOf(id.Name) != "common" {
					name = id.Name
				}
			}
		}
		domain := domainOf(name)
		if bodies[domain] == nil {
			bodies[domain] = new(bytes.Buffer)
			used[domain] = map[string]bool{}
		}
		bodies[domain].Write(src[fs.Position(start).Offset:fs.Position(decl.End()).Offset])
		bodies[domain].WriteString("\n\n")
		ast.Inspect(decl, func(n ast.Node) bool {
			if s, ok := n.(*ast.SelectorExpr); ok {
				if id, ok := s.X.(*ast.Ident); ok {
					used[domain][id.Name] = true
				}
			}
			return true
		})
	}
	out := map[string][]byte{}
	for domain, body := range bodies {
		var b bytes.Buffer
		b.WriteString(header)
		b.WriteString("import (\n")
		for _, imp := range f.Imports {
			path, _ := strconv.Unquote(imp.Path.Value)
			alias := filepath.Base(path)
			if imp.Name != nil {
				alias = imp.Name.Name
			}
			if used[domain][alias] {
				b.Write(src[fs.Position(imp.Pos()).Offset:fs.Position(imp.End()).Offset])
				b.WriteByte('\n')
			}
		}
		b.WriteString(")\n\n")
		b.Write(body.Bytes())
		data, err := format.Source(b.Bytes())
		if err != nil {
			return nil, err
		}
		out["api_"+domain+".gen.go"] = data
	}
	return out, nil
}

func run() error {
	dir, err := os.MkdirTemp("", "pennylane-sdkgen-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	target := filepath.Join(dir, "api.go")
	cmd := exec.Command("go", "tool", "oapi-codegen", "-config", "internal/spec/config.yaml", "-o", target, "internal/spec/company.json")
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return err
	}
	src, err := os.ReadFile(target)
	if err != nil {
		return err
	}
	spec, err := os.ReadFile("internal/spec/company.json")
	if err != nil {
		return err
	}
	files, err := split(src, spec)
	if err != nil {
		return err
	}
	for name, data := range files {
		if err := os.WriteFile(name, data, 0644); err != nil {
			return err
		}
	}
	stale, err := filepath.Glob("api_*.gen.go")
	if err != nil {
		return err
	}
	for _, name := range append(stale, "api.gen.go") {
		if _, ok := files[name]; ok {
			continue
		}
		if err := os.Remove(name); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	return nil
}
func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
